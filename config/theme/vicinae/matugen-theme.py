#!/usr/bin/env python3
"""Generate a Vicinae theme from Serpantinum's live matugen palette.

Serpantinum writes its current palette to
~/.local/state/serpantinum/qs_colors.json whenever a wallpaper or theme
changes. This script mirrors that palette into a Vicinae theme file so the
launcher keeps the same matugen vibe as the bar.

Run with --write-only to skip asking the running Vicinae server to reload.
"""

from __future__ import annotations

import json
import pathlib
import subprocess
import sys

HOME = pathlib.Path.home()
PALETTE = HOME / ".local/state/serpantinum/qs_colors.json"
THEME = HOME / ".local/share/vicinae/themes/matugen.toml"

FALLBACKS = {
    "base": "#1e1e2e",
    "mantle": "#181825",
    "crust": "#11111b",
    "text": "#cdd6f4",
    "subtext0": "#a6adc8",
    "subtext1": "#bac2de",
    "surface0": "#313244",
    "surface1": "#45475a",
    "surface2": "#585b70",
    "overlay0": "#6c7086",
    "overlay1": "#7f849c",
    "overlay2": "#9399b2",
    "blue": "#89b4fa",
    "sapphire": "#74c7ec",
    "peach": "#fab387",
    "green": "#a6e3a1",
    "red": "#f38ba8",
    "mauve": "#cba6f7",
    "pink": "#f5c2e7",
    "yellow": "#f9e2af",
    "maroon": "#eba0ac",
    "teal": "#94e2d5",
}


def color(palette: dict[str, object], key: str) -> str:
    value = palette.get(key)
    if isinstance(value, str) and value.startswith("#") and len(value) in (4, 7, 9):
        return value
    return FALLBACKS[key]


def render(palette: dict[str, object]) -> str:
    c = {key: color(palette, key) for key in FALLBACKS}
    return f"""\
# Generated from Serpantinum's live matugen palette.
# Do not edit by hand: changes are overwritten on the next theme change.

[meta]
version = 1
name = "Matugen"
description = "Wallpaper colours generated by Serpantinum's matugen"
variant = "dark"
inherits = "vicinae-dark"

[colors.core]
accent = "{c['blue']}"
accent_foreground = "{c['base']}"
background = "{c['base']}"
foreground = "{c['text']}"
secondary_background = "{c['mantle']}"
border = "{c['surface0']}"

[colors.main_window]
border = "{c['surface0']}"

[colors.settings_window]
border = "{c['surface1']}"

[colors.accents]
blue = "{c['blue']}"
green = "{c['green']}"
magenta = "{c['mauve']}"
orange = "{c['peach']}"
red = "{c['red']}"
yellow = "{c['yellow']}"
cyan = "{c['teal']}"
purple = "{c['pink']}"

[colors.text]
default = "{c['text']}"
muted = "{c['subtext0']}"
danger = "{c['red']}"
success = "{c['green']}"
placeholder = {{ name = "{c['overlay1']}", opacity = 0.6 }}

[colors.text.links]
default = "{c['blue']}"
visited = "{c['mauve']}"

[colors.text.selection]
background = "{c['blue']}"
foreground = "{c['base']}"

[colors.input]
background = "{c['mantle']}"
border = "{c['surface0']}"
border_focus = "{c['blue']}"
border_error = "{c['red']}"

[colors.button.primary]
background = "{c['surface1']}"
foreground = "{c['text']}"

[colors.button.primary.hover]
background = "{c['surface2']}"

[colors.button.primary.focus]
outline = "{c['blue']}"

[colors.list.item.hover]
background = "{c['surface0']}"
foreground = "{c['text']}"

[colors.list.item.selection]
background = "{c['surface1']}"
foreground = "{c['text']}"
secondary_background = "{c['surface2']}"
secondary_foreground = "{c['subtext0']}"

[colors.grid.item]
background = "{c['surface0']}"

[colors.grid.item.hover]
outline = {{ name = "{c['green']}", opacity = 0.8 }}

[colors.grid.item.selection]
outline = "{c['blue']}"

[colors.scrollbars]
background = "{c['surface0']}"
secondary_background = "{c['surface1']}"

[colors.tooltip]
background = "{c['mantle']}"
foreground = "{c['text']}"
border = "{c['surface0']}"

[colors.loading]
bar = "{c['blue']}"
spinner = "{c['blue']}"
"""


def main() -> int:
    try:
        palette = json.loads(PALETTE.read_text())
    except (OSError, json.JSONDecodeError):
        # Serpantinum has not generated a palette yet; keep the last theme.
        return 0

    THEME.parent.mkdir(parents=True, exist_ok=True)
    tmp = THEME.with_name(f".{THEME.name}.tmp")
    tmp.write_text(render(palette))
    tmp.replace(THEME)

    if "--write-only" not in sys.argv:
        subprocess.run(
            ["vicinae", "theme", "set", "matugen"],
            check=False,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
